const GLYPH_H = 9;
const parsed = new Map();
for (const [ch, def] of Object.entries(G)) {
    const rows = def.split("/");
    const w = Math.max(...rows.map((r) => r.length));
    while (rows.length < GLYPH_H) rows.push(".".repeat(w));
    parsed.set(ch, { w, rows });
}
const SPACE_W = 3, GAP = 1;

const atlases = new Map();
function atlas(color) {
    let a = atlases.get(color);
    if (a) return a;
    const entries = [...parsed.entries()];
    const width = entries.reduce((s, [, g]) => s + g.w + 1, 0);
    const canvas = makeCanvas(width, GLYPH_H);
    const ctx = canvas.getContext("2d");
    ctx.fillStyle = color;
    const pos = new Map();
    let x = 0;
    for (const [ch, g] of entries) {
        pos.set(ch, x);
        g.rows.forEach((row, y) => { for (let i = 0; i < row.length; i++) if (row[i] === "#") ctx.fillRect(x + i, y, 1, 1); });
        x += g.w + 1;
    }
    a = { canvas, pos };
    atlases.set(color, a);
    return a;
}

function glyph(ch) {
    return parsed.get(ch) ?? parsed.get(ch.toUpperCase()) ?? parsed.get("?");
}

function lineWidth(text) {
    let w = 0;
    for (const ch of text) w += (ch === " " ? SPACE_W : glyph(ch).w) + GAP;
    return Math.max(0, w - GAP);
}

export const LINE_HEIGHT = 10;

export function measureText(text, scale = 1) {
    return Math.max(...String(text).split("\n").map(lineWidth)) * scale;
}

// y is the top of the text line (cap top).
export function drawText(ctx, text, x, y, { color = "#e8e6f0", align = "left", scale = 1, shadow = true, shadowColor = "#07060c" } = {}) {
    const lines = String(text).split("\n");
    const prevSmoothing = ctx.imageSmoothingEnabled;
    ctx.imageSmoothingEnabled = false;
    const passes = shadow ? [[shadowColor, scale, scale], [color, 0, 0]] : [[color, 0, 0]];
    for (const [col, dx, dy] of passes) {
        const a = atlas(col);
        lines.forEach((ln, li) => {
            const w = lineWidth(ln) * scale;
            let cx = Math.round(align === "center" ? x - w / 2 : align === "right" ? x - w : x) + dx;
            const cy = Math.round(y + li * LINE_HEIGHT * scale) + dy;
            for (const ch of ln) {
                if (ch === " ") { cx += (SPACE_W + GAP) * scale; continue; }
                const g = glyph(ch);
                const key = parsed.has(ch) ? ch : parsed.has(ch.toUpperCase()) ? ch.toUpperCase() : "?";
                ctx.drawImage(a.canvas, a.pos.get(key), 0, g.w, GLYPH_H, cx, cy, g.w * scale, GLYPH_H * scale);
                cx += (g.w + GAP) * scale;
            }
        });
    }
    ctx.imageSmoothingEnabled = prevSmoothing;
}
